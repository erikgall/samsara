## Samsara SDK

- Use `samsara-sdk-development` for application work with `erikgall/samsara` v2.
- Use `upgrade-samsara-sdk-v2` for migrations from v1.1 to v2.
- `UnsupportedOperationException` means the SDK deliberately does not wrap that operation. Do not bypass it with a raw request unless the application owner accepts that integration.
